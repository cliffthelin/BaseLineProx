# -- pure diff engine -------------------------------------------------

def test_diff_config_reports_changed_and_unchanged_keys():
    current = {"a": 1, "b": 2, "c": 3}
    desired = {"a": 1, "b": 99, "c": 3}
    result = cd.diff_config(current, desired)
    by_key = {row["key"]: row for row in result}
    assert by_key["a"]["changed"] is False
    assert by_key["b"]["changed"] is True
    assert by_key["b"]["current"] == 2
    assert by_key["b"]["desired"] == 99
    assert by_key["c"]["changed"] is False


def test_diff_config_only_reports_keys_present_in_desired():
    current = {"a": 1, "unrelated_key": "x"}
    desired = {"a": 1}
    result = cd.diff_config(current, desired)
    assert [row["key"] for row in result] == ["a"]


def test_diff_config_treats_a_missing_current_key_as_changed():
    current = {}
    desired = {"a": 1}
    result = cd.diff_config(current, desired)
    assert result[0]["changed"] is True
    assert result[0]["current"] is None


# -- top-level: builds the full DIFFERENCES report -------------------------

def test_compute_full_diff_covers_all_four_real_subsystems():
    runner = FakeRunner(command_responses=[
        (lambda a: a[:1] == ["ethtool"] and len(a) == 2, FakeProc(0, ETHTOOL_SETTINGS_OUTPUT, "")),
        (lambda a: a[:2] == ["ethtool", "-k"], FakeProc(0, ETHTOOL_FEATURES_OUTPUT, "")),
        (lambda a: a[:2] == ["ethtool", "-a"], FakeProc(0, ETHTOOL_PAUSE_OUTPUT, "")),
        (lambda a: a[:1] == ["dpkg-query"] and "amd64-microcode" in a, FakeProc(1, "", "not found")),
        (lambda a: a[:1] == ["dpkg-query"] and "firmware-mediatek" in a, FakeProc(0, "install ok installed", "")),
    ])
    desired_config = {
        "proxmox": {"smartd_health_check": True, "ethtool_speed": "1000"},
        "drivers": {"cpu_microcode": True, "cpu_microcode_package": "amd64-microcode",
                    "nic_wifi_firmware": True, "wifi_firmware_package": "firmware-mediatek"},
    }
    report = cd.compute_full_diff(runner, desired_config, network_interface="eth0")
    sections = {s["subsystem"] for s in report}
    assert sections == {"smartd", "ethtool", "cpu_microcode", "wifi_firmware"}
    smartd_section = next(s for s in report if s["subsystem"] == "smartd")
    assert any(row["key"] == "smartd_health_check" and row["changed"] for row in smartd_section["changes"])
    cpu_section = next(s for s in report if s["subsystem"] == "cpu_microcode")
    assert cpu_section["changes"][0]["changed"] is True  # not installed yet, desired wants it
    wifi_section = next(s for s in report if s["subsystem"] == "wifi_firmware")
    assert wifi_section["changes"][0]["changed"] is False  # already installed, matches desired
