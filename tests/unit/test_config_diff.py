"""Unit tests for config_diff.py - real read-back of the target
system's CURRENT state for the four subsystems config_pipeline.py can
actually apply (smartd, ethtool, cpu_microcode, wifi_firmware), and a
pure diff against a DESIRED exported config. This is the real engine
behind the configurator's "DIFFERENCES" page - no real smartd/ethtool/
dpkg is ever invoked, the FakeRunner records/returns everything.

The smartd.conf round-trip is exact by construction: config_apply.
build_smartd_conf() controls the only format ever written, so parsing
it back is a real, deterministic round-trip, not a guess. The ethtool
read-back format is real, standard `ethtool(8)`/`ethtool -k`/
`ethtool -a` output shape - the same one `man ethtool` and every real
Linux system produce.
"""
from fake_runner import FakeProc, FakeRunner

import config_diff as cd


# -- smartd.conf read-back -------------------------------------------------

def test_read_current_smartd_config_absent_file_returns_all_defaults():
    runner = FakeRunner()  # /etc/smartd.conf not present
    current = cd.read_current_smartd_config(runner)
    assert current == {
        "smartd_health_check": False, "smartd_monitor_all": False,
        "smartd_auto_offline": "", "smartd_attribute_autosave": "",
        "smartd_selftest_schedule": "", "smartd_email": "", "smartd_email_frequency": "",
    }


def test_read_current_smartd_config_parses_a_real_generated_file():
    content = ("# Generated by config_apply.py - do not edit by hand\n"
               "DEVICESCAN -H -a -o on -S on -s L/../../7/03 -m ops@example.com -M daily\n")
    runner = FakeRunner(files={"/etc/smartd.conf": content})
    current = cd.read_current_smartd_config(runner)
    assert current == {
        "smartd_health_check": True, "smartd_monitor_all": True,
        "smartd_auto_offline": "on", "smartd_attribute_autosave": "on",
        "smartd_selftest_schedule": "L/../../7/03",
        "smartd_email": "ops@example.com", "smartd_email_frequency": "daily",
    }


def test_read_current_smartd_config_omitted_email_directives_read_back_blank():
    content = "# Generated by config_apply.py - do not edit by hand\nDEVICESCAN -H -a -o on -S on -s L/../../7/03\n"
    runner = FakeRunner(files={"/etc/smartd.conf": content})
    current = cd.read_current_smartd_config(runner)
    assert current["smartd_email"] == ""
    assert current["smartd_email_frequency"] == ""


# -- ethtool read-back -------------------------------------------------

ETHTOOL_SETTINGS_OUTPUT = """Settings for eth0:
	Supported ports: [ TP ]
	Speed: 1000Mb/s
	Duplex: Full
	Auto-negotiation: on
	Wake-on: g
	Link detected: yes
"""

ETHTOOL_FEATURES_OUTPUT = """Features for eth0:
rx-checksumming: on
tx-checksumming: on
	tx-checksum-ipv4: off [fixed]
tcp-segmentation-offload: on
generic-receive-offload: off
"""

ETHTOOL_PAUSE_OUTPUT = """Pause parameters for eth0:
Autonegotiate:	on
RX:		off
TX:		off
"""


def test_read_current_ethtool_config_parses_real_tool_output():
    runner = FakeRunner(command_responses=[
        (lambda a: a[:1] == ["ethtool"] and len(a) == 2, FakeProc(0, ETHTOOL_SETTINGS_OUTPUT, "")),
        (lambda a: a[:2] == ["ethtool", "-k"], FakeProc(0, ETHTOOL_FEATURES_OUTPUT, "")),
        (lambda a: a[:2] == ["ethtool", "-a"], FakeProc(0, ETHTOOL_PAUSE_OUTPUT, "")),
    ])
    current = cd.read_current_ethtool_config(runner, "eth0")
    assert current == {
        "ethtool_autoneg": "on", "ethtool_speed": "1000", "ethtool_duplex": "full", "ethtool_wol": "g",
        "ethtool_rx_checksum": True, "ethtool_tx_checksum": True,
        "ethtool_tso": True, "ethtool_gro": False,
        "ethtool_pause_autoneg": True,
    }


def test_read_current_ethtool_config_handles_a_real_command_failure():
    runner = FakeRunner(command_responses=[
        (lambda a: a[:1] == ["ethtool"], FakeProc(1, "", "no such device")),
    ])
    current = cd.read_current_ethtool_config(runner, "eth0")
    assert current["ethtool_autoneg"] == ""


